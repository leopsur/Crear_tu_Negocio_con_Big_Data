"""
01_crear_bases_datos.py - Crea las 10 tablas del diagrama Entidad-Relación de
ActivityLeo en las 3 bases de datos (MySQL, PostgreSQL y MariaDB).

Uso:  python 01_crear_bases_datos.py
"""
from config import BASES_DE_DATOS, conectar

# Orden de creación: primero las tablas de las que dependen las demás.
TABLAS = [
    "Alumnos", "Vecinos", "Categorias_Interes", "Espacios_disponibles",
    "Preferencias_Alumnos", "Preferencias_Vecinos", "Tendencias_Redes",
    "Propuestas_actividades", "Votaciones", "Actividades_finales",
]

# MySQL y MariaDB (misma sintaxis)

DDL_MYSQL = [
    """CREATE TABLE Alumnos (
        id_alumno INT AUTO_INCREMENT PRIMARY KEY,
        nombre VARCHAR(100) NOT NULL,
        curso VARCHAR(30) NOT NULL,
        fecha_nacimiento DATE NOT NULL,
        correo_institucional VARCHAR(150) NOT NULL UNIQUE
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Vecinos (
        id_vecino INT AUTO_INCREMENT PRIMARY KEY,
        nombre VARCHAR(100) NOT NULL,
        codigo_postal VARCHAR(10) NOT NULL,
        rango_edad VARCHAR(20) NOT NULL
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Categorias_Interes (
        id_categoria INT AUTO_INCREMENT PRIMARY KEY,
        nombre_categoria VARCHAR(60) NOT NULL UNIQUE,
        descripcion VARCHAR(255)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Espacios_disponibles (
        id_espacio INT AUTO_INCREMENT PRIMARY KEY,
        nombre_espacio VARCHAR(100) NOT NULL,
        capacidad_maxima INT NOT NULL
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Preferencias_Alumnos (
        id_preferencia INT AUTO_INCREMENT PRIMARY KEY,
        id_alumno INT NOT NULL,
        id_categoria INT NOT NULL,
        nivel_interes INT NOT NULL,
        FOREIGN KEY (id_alumno) REFERENCES Alumnos(id_alumno),
        FOREIGN KEY (id_categoria) REFERENCES Categorias_Interes(id_categoria)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Preferencias_Vecinos (
        id_preferencia_vec INT AUTO_INCREMENT PRIMARY KEY,
        id_vecino INT NOT NULL,
        id_categoria INT NOT NULL,
        frecuencia_deseada VARCHAR(20) NOT NULL,
        FOREIGN KEY (id_vecino) REFERENCES Vecinos(id_vecino),
        FOREIGN KEY (id_categoria) REFERENCES Categorias_Interes(id_categoria)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Tendencias_Redes (
        id_tendencia INT AUTO_INCREMENT PRIMARY KEY,
        id_categoria INT NOT NULL,
        palabra_clave VARCHAR(100) NOT NULL,
        volumen_busquedas INT NOT NULL,
        FOREIGN KEY (id_categoria) REFERENCES Categorias_Interes(id_categoria)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Propuestas_actividades (
        id_propuesta INT AUTO_INCREMENT PRIMARY KEY,
        id_categoria INT NOT NULL,
        titulo_propuesta VARCHAR(200) NOT NULL,
        origen VARCHAR(20) NOT NULL,
        FOREIGN KEY (id_categoria) REFERENCES Categorias_Interes(id_categoria)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Votaciones (
        id_voto INT AUTO_INCREMENT PRIMARY KEY,
        id_propuesta INT NOT NULL,
        id_alumno INT NULL,
        id_vecino INT NULL,
        FOREIGN KEY (id_propuesta) REFERENCES Propuestas_actividades(id_propuesta),
        FOREIGN KEY (id_alumno) REFERENCES Alumnos(id_alumno),
        FOREIGN KEY (id_vecino) REFERENCES Vecinos(id_vecino)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",

    """CREATE TABLE Actividades_finales (
        id_actividad INT AUTO_INCREMENT PRIMARY KEY,
        id_propuesta INT NOT NULL,
        id_espacio INT NOT NULL,
        horario_fijo DATETIME NOT NULL,
        FOREIGN KEY (id_propuesta) REFERENCES Propuestas_actividades(id_propuesta),
        FOREIGN KEY (id_espacio) REFERENCES Espacios_disponibles(id_espacio)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4""",
]

# PostgreSQL

DDL_POSTGRES = [
    """CREATE TABLE Alumnos (
        id_alumno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre VARCHAR(100) NOT NULL,
        curso VARCHAR(30) NOT NULL,
        fecha_nacimiento DATE NOT NULL,
        correo_institucional VARCHAR(150) NOT NULL UNIQUE
    )""",

    """CREATE TABLE Vecinos (
        id_vecino INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre VARCHAR(100) NOT NULL,
        codigo_postal VARCHAR(10) NOT NULL,
        rango_edad VARCHAR(20) NOT NULL
    )""",

    """CREATE TABLE Categorias_Interes (
        id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre_categoria VARCHAR(60) NOT NULL UNIQUE,
        descripcion VARCHAR(255)
    )""",

    """CREATE TABLE Espacios_disponibles (
        id_espacio INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        nombre_espacio VARCHAR(100) NOT NULL,
        capacidad_maxima INTEGER NOT NULL
    )""",

    """CREATE TABLE Preferencias_Alumnos (
        id_preferencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_alumno INTEGER NOT NULL REFERENCES Alumnos(id_alumno),
        id_categoria INTEGER NOT NULL REFERENCES Categorias_Interes(id_categoria),
        nivel_interes INTEGER NOT NULL
    )""",

    """CREATE TABLE Preferencias_Vecinos (
        id_preferencia_vec INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_vecino INTEGER NOT NULL REFERENCES Vecinos(id_vecino),
        id_categoria INTEGER NOT NULL REFERENCES Categorias_Interes(id_categoria),
        frecuencia_deseada VARCHAR(20) NOT NULL
    )""",

    """CREATE TABLE Tendencias_Redes (
        id_tendencia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_categoria INTEGER NOT NULL REFERENCES Categorias_Interes(id_categoria),
        palabra_clave VARCHAR(100) NOT NULL,
        volumen_busquedas INTEGER NOT NULL
    )""",

    """CREATE TABLE Propuestas_actividades (
        id_propuesta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_categoria INTEGER NOT NULL REFERENCES Categorias_Interes(id_categoria),
        titulo_propuesta VARCHAR(200) NOT NULL,
        origen VARCHAR(20) NOT NULL
    )""",

    """CREATE TABLE Votaciones (
        id_voto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_propuesta INTEGER NOT NULL REFERENCES Propuestas_actividades(id_propuesta),
        id_alumno INTEGER NULL REFERENCES Alumnos(id_alumno),
        id_vecino INTEGER NULL REFERENCES Vecinos(id_vecino)
    )""",

    """CREATE TABLE Actividades_finales (
        id_actividad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        id_propuesta INTEGER NOT NULL REFERENCES Propuestas_actividades(id_propuesta),
        id_espacio INTEGER NOT NULL REFERENCES Espacios_disponibles(id_espacio),
        horario_fijo TIMESTAMP NOT NULL
    )""",
]


def crear_tablas(nombre_bd):
    cfg = BASES_DE_DATOS[nombre_bd]
    print(f"\n== {nombre_bd} ==")
    conexion = conectar(nombre_bd)
    cursor = conexion.cursor()

    if cfg["tipo"] == "mysql":
        cursor.execute("SET FOREIGN_KEY_CHECKS = 0")
        for tabla in reversed(TABLAS):
            cursor.execute(f"DROP TABLE IF EXISTS {tabla}")
        cursor.execute("SET FOREIGN_KEY_CHECKS = 1")
        ddl = DDL_MYSQL
    else:
        for tabla in reversed(TABLAS):
            cursor.execute(f"DROP TABLE IF EXISTS {tabla} CASCADE")
        ddl = DDL_POSTGRES

    for sentencia in ddl:
        cursor.execute(sentencia)
    conexion.commit()
    conexion.close()
    print(f"  {len(ddl)} tablas creadas")


if __name__ == "__main__":
    for bd in BASES_DE_DATOS:
        crear_tablas(bd)
    print("\nListo: las 3 bases de datos tienen sus 10 tablas.")
